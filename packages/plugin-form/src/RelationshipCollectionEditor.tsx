  /** React-only row layout; `rows` removes the card shell but keeps the same ObjectForm controls. */
  presentation?: 'cards' | 'rows';
  /** Field grid density used by ObjectForm; `rows` defaults to three columns, capped by field count. */
  columns?: number;
  title?: string;
  itemLabel?: string;
  addLabel?: string;
  removeLabel?: string;
  className?: string;
