function schemaRequestKey(parentObjectName: string, childObjectName: string, relationshipField?: string): string {
  return `${parentObjectName}\u0000${childObjectName}\u0000${relationshipField ?? ''}`;
}

function fieldGridClasses(columns: number): string {
  const base = 'grid gap-x-[var(--ui-form-column-gap,1rem)] gap-y-[var(--ui-form-row-gap,1rem)]';
  if (columns <= 1) return 'space-y-[var(--ui-form-row-gap,1rem)]';
  if (columns === 2) return `${base} md:grid-cols-2`;
  if (columns === 3) return `${base} md:grid-cols-2 lg:grid-cols-3`;
  return `${base} md:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4`;
}

